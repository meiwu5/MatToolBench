import numpy as np

def read_poscar(filename='POSCAR'):
    
    result = {}
    
    with open(filename, 'r') as f:
        lines = f.readlines()
    
    result['title'] = lines[0].strip()
    
    result['scale'] = float(lines[1].strip())
    
    lattice = []
    for i in range(2, 5):
        lattice.append([float(x) for x in lines[i].strip().split()])
    result['lattice'] = np.array(lattice)
    
    atom_types = lines[5].strip().split()
    result['atom_types'] = atom_types
    
    atom_numbers = [int(x) for x in lines[6].strip().split()]
    result['atom_numbers'] = atom_numbers
    result['total_atoms'] = sum(atom_numbers)
    
    line_idx = 7
    coordinate_type = lines[line_idx].strip().upper()
    result['coordinate_type'] = coordinate_type
    
    selective_dynamics = False
    if coordinate_type in ['SEL', 'SELECTIVE']:
        selective_dynamics = True
        coordinate_type = lines[line_idx+1].strip().upper()
        result['coordinate_type'] = coordinate_type
        line_idx += 1
    
    positions = []
    if selective_dynamics:
        for i in range(line_idx+1, line_idx+1+result['total_atoms']):
            parts = lines[i].strip().split()
            positions.append([float(x) for x in parts[:3]])
    else:
        for i in range(line_idx+1, line_idx+1+result['total_atoms']):
            parts = lines[i].strip().split()
            positions.append([float(x) for x in parts[:3]])
    
    result['positions'] = np.array(positions)
    
    if selective_dynamics:
        selective_flags = []
        for i in range(line_idx+1, line_idx+1+result['total_atoms']):
            parts = lines[i].strip().split()
            flags = [x.upper() == 'T' for x in parts[3:6]]
            selective_flags.append(flags)
        result['selective_dynamics'] = np.array(selective_flags)
    
    if len(lines) > line_idx + result['total_atoms'] + 1:
        velocities = []
        for i in range(line_idx + result['total_atoms'] + 1, len(lines)):
            parts = lines[i].strip().split()
            if not parts:
                continue
            velocities.append([float(x) for x in parts[:3]])
        if velocities:
            result['velocities'] = np.array(velocities)
    
    return result

def write_poscar(structure_data, filename='POSCAR_redlatt', direct=True):

    try:
        with open(filename, 'w') as f:
            f.write(f"{structure_data.get('title', 'Generated by Python')}\n")
            
            f.write(f"{structure_data.get('scale', 1.0):.10f}\n")
            
            lattice = structure_data.get('lattice', np.eye(3))
            for vec in lattice:
                f.write(f" {vec[0]:20.16f} {vec[1]:20.16f} {vec[2]:20.16f}\n")
            
            atom_types = structure_data.get('atom_types', ['X'])
            f.write(' '.join(atom_types) + '\n')
            
            atom_numbers = structure_data.get('atom_numbers', [1])
            f.write(' '.join([str(n) for n in atom_numbers]) + '\n')
            
            if direct:
                f.write('Direct\n')
            else:
                f.write('Cartesian\n')
            
            positions = structure_data.get('positions', np.zeros((sum(atom_numbers), 3)))
            
            if 'selective_dynamics' in structure_data:
                selective_flags = structure_data['selective_dynamics']
                for i, pos in enumerate(positions):
                    flags = ['T' if f else 'F' for f in selective_flags[i]]
                    f.write(f" {pos[0]:20.16f} {pos[1]:20.16f} {pos[2]:20.16f} {' '.join(flags)}\n")
            else:
                for pos in positions:
                    f.write(f" {pos[0]:20.16f} {pos[1]:20.16f} {pos[2]:20.16f}\n")
            
            if 'velocities' in structure_data:
                f.write('Selective dynamics\n')
                if direct:
                    f.write('Direct\n')
                else:
                    f.write('Cartesian\n')
                
                velocities = structure_data['velocities']
                for vel in velocities:
                    f.write(f" {vel[0]:20.16f} {vel[1]:20.16f} {vel[2]:20.16f}\n")
            
        return True
    except Exception as e:
        #print(f"写入POSCAR文件时出错: {e}")
        return False

